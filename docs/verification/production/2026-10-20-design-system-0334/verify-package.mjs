// Run against the frozen native build; only temporary copies of the demo are opened.
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync, spawnSync} from 'node:child_process';
import {snapshotPackage} from '../../../../plugin-src/src/lib/package-snapshot.mjs';
import {validateInstallerMarketplace} from '../../../../workbench/scripts/dist.mjs';
import {exportColleagueDelivery} from '../../../../workbench/scripts/export-colleague-delivery.mjs';
import {assertMachO, copyNativeArtifact, validateNativeArtifact} from '../../../../workbench/scripts/native-payload.mjs';

const root = path.resolve(import.meta.dirname, '../../../..');
const [buildSource, buildDmg, sourceCommit, archiveRepo, deliveryDirectory, nativeArtifact] = process.argv.slice(2);
assert.equal(process.argv.length, 8, 'Use verify-package.mjs <built.app> <built.dmg> <commit> <archive repo> <new delivery directory> <fresh native artifact>');
const version = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8')).version;
const git = args => execFileSync('git', ['-C', root, ...args], {encoding: 'utf8'}).trim();
assert.match(sourceCommit, /^[a-f0-9]{40}$/);
assert.equal(git(['rev-parse', 'HEAD']), sourceCommit);
assert.equal(git(['diff', 'HEAD', '--name-only']), '', 'Tracked source must remain frozen');
assert.ok(buildSource.endsWith('/mac-arm64/自媒体工作台.app'));
assert.equal(path.basename(buildDmg), `Nova-Content-Hub-${version}-darwin-arm64-preview.dmg`);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const artifactBytes = await fs.readFile(path.join(nativeArtifact, 'artifact.json'));
const metadata = JSON.parse(artifactBytes);
assert.equal(metadata.source.commit, sourceCommit);
assert.equal(metadata.source.config.version, version);
assert.deepEqual(metadata.source.config, JSON.parse(execFileSync('git', ['-C', root, 'show', `${sourceCommit}:release.config.json`], {encoding: 'utf8'})));
for (const [file, digest] of Object.entries(metadata.source.locks)) assert.equal(hash(execFileSync('git', ['-C', root, 'show', `${sourceCommit}:${file}`])), digest);
let artifact = await validateNativeArtifact(nativeArtifact, metadata.source, 'arm64');
const preservedArtifact = path.join(archiveRepo, 'workbench/release/native-payloads', sourceCommit, 'darwin-arm64-design-system');
await fs.mkdir(path.dirname(preservedArtifact), {recursive: true});
await copyNativeArtifact(artifact, preservedArtifact, metadata.source);
artifact = await validateNativeArtifact(preservedArtifact, metadata.source, 'arm64');
const built = await snapshotPackage(buildSource);
const parent = path.join(archiveRepo, 'workbench/release/darwin-arm64/preview');
const source = path.join(parent, `.packaged-apps.noindex/build-${version.replaceAll('.', '')}-${sourceCommit.slice(0, 7)}/mac-arm64/自媒体工作台.app`);
const dmg = path.join(parent, path.basename(buildDmg));
await assert.rejects(fs.lstat(source), {code: 'ENOENT'});
await assert.rejects(fs.lstat(dmg), {code: 'ENOENT'});
await fs.mkdir(path.dirname(source), {recursive: true});
execFileSync('/usr/bin/ditto', [buildSource, source]);
await fs.copyFile(buildDmg, dmg, (await import('node:fs')).constants.COPYFILE_EXCL);
assert.deepEqual(await snapshotPackage(source), built);
const dmgSha256 = hash(await fs.readFile(buildDmg));
assert.equal(hash(await fs.readFile(dmg)), dmgSha256);
execFileSync('/usr/bin/codesign', ['--verify', '--deep', '--strict', source]);
const signature = spawnSync('/usr/bin/codesign', ['-dvv', source], {encoding: 'utf8'});
assert.equal(signature.status, 0);
assert.match(signature.stdout + signature.stderr, /Signature=adhoc/);
await fs.writeFile(path.join(import.meta.dirname, 'codesign.log'), signature.stdout + signature.stderr);
const resources = path.join(source, 'Contents/Resources');
const release = JSON.parse(await fs.readFile(path.join(resources, 'app/workbench/dist/release.json'), 'utf8'));
assert.equal(release.version, version);
assert.equal(release.AUTH_MODE, 'disabled');
assert.equal(release.productionReady, false);
assert.equal(release.platform, 'darwin');
assert.equal(release.arch, 'arm64');
const plist = JSON.parse(execFileSync('/usr/bin/plutil', ['-convert', 'json', '-o', '-', path.join(source, 'Contents/Info.plist')], {encoding: 'utf8'}));
assert.equal(plist.CFBundleDisplayName, '自媒体工作台');
assert.equal(plist.CFBundleShortVersionString, version);
assert.equal(plist.CFBundleVersion, version);
assert.equal(plist.NSHumanReadableCopyright, '© 2026 杭州新岛橙灵智能科技有限责任公司');
const appPackage = JSON.parse(await fs.readFile(path.join(resources, 'app/package.json'), 'utf8'));
assert.equal(appPackage.version, version);
assert.deepEqual(appPackage.author, {name: '杭州新岛橙灵智能科技有限责任公司'});
for (const relative of ['workbench/dist', 'plugin-src/src/lib', 'plugin-src/resources', 'plugin-src/src/bridge']) assert.deepEqual(await snapshotPackage(path.join(resources, 'app', relative)), await snapshotPackage(path.join(artifact.path, 'payload', relative)), `Final ${relative} matches frozen native artifact`);
const nativeFiles = Object.keys(built).filter(file => built[file].sha256 && (file.endsWith('.node') || file.endsWith('.dylib') || file.startsWith('Contents/MacOS/') || file === 'Contents/Frameworks/Electron Framework.framework/Versions/A/Electron Framework'));
assert.ok(nativeFiles.some(file => file.endsWith('.node')));
assert.ok(nativeFiles.some(file => file.includes('Electron Framework')));
for (const file of nativeFiles) assertMachO(await fs.readFile(path.join(source, file)), 'arm64');
const market = path.join(resources, 'plugin-marketplace');
const pluginRelease = JSON.parse(await fs.readFile(path.join(market, 'nova-content-hub/plugin-src/src/release.json'), 'utf8'));
assert.deepEqual(pluginRelease, {...release, format: 'nova-content-plugin-release'});
await validateInstallerMarketplace(market, pluginRelease);
const shared = 'plugin-src/src/lib/file-library/index.mjs';
const sharedHash = hash(execFileSync('git', ['-C', root, 'show', `${sourceCommit}:${shared}`]));
for (const prefix of ['app', 'plugin-marketplace/nova-content-hub']) assert.equal(hash(await fs.readFile(path.join(resources, prefix, shared))), sharedHash);
assert.deepEqual(Object.keys(built).filter(file => /(?:^|\/)(?:tests?|__tests__)\/|(?:\.test|\.spec)\.|probe\.mjs$/.test(file)), []);
for (const prefix of ['Contents/Resources/app/workbench/src/', 'Contents/Resources/app/workbench/scripts/', 'Contents/Resources/app/.local-probes/']) assert.ok(!Object.keys(built).some(file => file.startsWith(prefix)));
const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'nova-a-release-'));
const mount = path.join(temporary, 'mount');
await fs.mkdir(mount);
let mounted = false;
try {
  execFileSync('/usr/bin/hdiutil', ['attach', dmg, '-readonly', '-nobrowse', '-mountpoint', mount, '-plist'], {stdio: 'pipe'});
  mounted = true;
  assert.deepEqual(await snapshotPackage(path.join(mount, '自媒体工作台.app')), built);
  const demo = path.join(temporary, 'AI自媒体示例库');
  await fs.cp(path.join(mount, 'AI自媒体示例库'), demo, {recursive: true});
  const {openLibrary} = await import(path.join(resources, 'app', shared));
  const library = openLibrary(demo), contents = library.listContents();
  assert.equal(library.listTemplates().length, 20);
  assert.equal(library.listPrompts().length, 52);
  assert.equal(contents.length, 1);
  const content = library.readContent(contents[0].id);
  const provenance = JSON.parse(await fs.readFile(path.join(resources, 'app/plugin-src/resources/builtin-examples/provenance.json'), 'utf8'));
  assert.equal(content.isExample, true);
  assert.equal(content.candidates.length, 2);
  assert.deepEqual(content.candidates.map(candidate => candidate.assetHash), provenance.hashes);
  assert.equal(content.plans.length, 0);
  assert.equal(content.publications.length, 0);
  await exportColleagueDelivery(dmg, deliveryDirectory);
  assert.deepEqual((await fs.readdir(deliveryDirectory)).sort(), ['SHA256SUMS.txt', '安装与使用.txt', `自媒体工作台-${version}-Mac苹果芯片.dmg`]);
  assert.equal(hash(await fs.readFile(path.join(deliveryDirectory, `自媒体工作台-${version}-Mac苹果芯片.dmg`))), dmgSha256);
  assert.equal(git(['rev-parse', 'HEAD']), sourceCommit);
  assert.equal(git(['diff', 'HEAD', '--name-only']), '');
  const stats = await fs.stat(dmg);
  const receipt = {recordedAt: new Date().toISOString(), version, sourceCommit, source, dmg, dmgSha256, treeSha256: hash(JSON.stringify(built)), entries: Object.keys(built).length, deliveryDirectory, release, archivedBuildEqualsDmg: true, pairedMarketplaceVerified: true, developerIdSigned: false, notarized: false, companyMetadataVerified: true, engineeringFilesExcluded: true, nativeArtifact: {path: artifact.path, manifestSha256: hash(artifactBytes), source: artifact.source, nativeFiles}, demo: {templates: 20, prompts: 52, contents: 1, originalHashes: provenance.hashes}, actualProperties: {dmgBytes: stats.size, dmgModifiedAt: stats.mtime.toISOString()}, userLibraryAccessed: false};
  await fs.writeFile(path.join(import.meta.dirname, 'package.json'), JSON.stringify(receipt, null, 2) + '\n');
  console.log(JSON.stringify({status: 'PASS', ...receipt}));
} finally {
  if (mounted) execFileSync('/usr/bin/hdiutil', ['detach', mount], {stdio: 'pipe'});
}
