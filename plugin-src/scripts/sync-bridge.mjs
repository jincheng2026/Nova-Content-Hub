import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const source = new URL('../src/bridge/handoff.js', import.meta.url);
const target = new URL('../../原型/shared/handoff.js', import.meta.url);
const header = '// Generated by plugin-src/scripts/sync-bridge.mjs; edit plugin-src/src/bridge/handoff.js.\n';

export async function syncBridge(check = false) {
  const expected = header + await readFile(source, 'utf8');
  if (check) {
    if (await readFile(target, 'utf8') !== expected) throw Error('Generated prototype bridge drift; run node plugin-src/scripts/sync-bridge.mjs');
  } else await writeFile(target, expected);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || args.length === 1 && args[0] !== '--check') throw Error('Use sync-bridge.mjs [--check]');
  await syncBridge(args[0] === '--check');
}
