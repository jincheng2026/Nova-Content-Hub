import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createVault, openVault} from '../index.mjs';
import {createDefaultSourceMap, resolveSource, linkSource, readSourceMap, importSource, readBoundSourceFile} from '../source-map.mjs';
const fixture=t=>{const root=fs.mkdtempSync(path.join(os.tmpdir(),'source-map-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));return root;};
test('new vault does not provision excluded X sources or directories',t=>{
    const root=fixture(t);
    createVault(root);
    assert.equal(fs.existsSync(path.join(root,'13_X收藏')),false);
    assert.equal(readSourceMap(root).sources.some(source=>source.role==='bookmarks'),false);
    assert.throws(()=>resolveSource(root,'bookmarks'),/SOURCE_NOT_LINKED/);
});
test('default source configuration leaves existing unconfigured X history untouched',t=>{
    const root=fixture(t),history=path.join(root,'13_X收藏');
    fs.mkdirSync(history);
    fs.writeFileSync(path.join(history,'历史.md'),'作者历史收藏');
    const map=createDefaultSourceMap(root,{createDirectories:true});
    assert.equal(map.sources.some(source=>source.role==='bookmarks'),false);
    assert.equal(fs.readFileSync(path.join(history,'历史.md'),'utf8'),'作者历史收藏');
});
test('opening an old vault without a source map does not add an X source',t=>{
    const root=fixture(t);
    for(const p of ['00_个人背景','04_选题库','05_内容草稿'])fs.mkdirSync(path.join(root,p));
    openVault(root);
    assert.equal(readSourceMap(root).sources.some(source=>source.role==='bookmarks'),false);
    assert.equal(fs.existsSync(path.join(root,'13_X收藏')),false);
});
test('existing X source maps and explicitly linked X imports remain readable',t=>{
    const root=fixture(t),external=fixture(t);
    createVault(root);
    fs.mkdirSync(path.join(root,'13_X收藏'),{recursive:true});
    fs.writeFileSync(path.join(root,'13_X收藏','历史.md'),'作者历史收藏');
    const map=readSourceMap(root);
    if(!map.sources.some(source=>source.id==='bookmarks'))map.sources.push({id:'bookmarks',role:'bookmarks',mode:'internal',root:'13_X收藏',format:'files',authority:'official',writable:true});
    const mapFile=path.join(root,'.workbench/source-map.json');
    fs.writeFileSync(mapFile,JSON.stringify(map));
    const before=fs.readFileSync(mapFile);
    createDefaultSourceMap(root,{createDirectories:true});
    openVault(root);
    assert.deepEqual(fs.readFileSync(mapFile),before);
    assert.equal(readBoundSourceFile(root,{sourceId:'bookmarks',relativePath:'历史.md'}).data.toString(),'作者历史收藏');
    fs.writeFileSync(path.join(external,'收藏.md'),'显式关联收藏');
    const linked=linkSource(root,{role:'bookmarks',selectedRoot:external,authority:'official'});
    const file=readBoundSourceFile(root,{sourceId:linked.id,relativePath:'收藏.md'});
    assert.equal(file.data.toString(),'显式关联收藏');
    const record=importSource(root,{sourceId:linked.id,selectedEntries:['收藏.md'],expectedHashes:{'收藏.md':file.hash}});
    assert.equal(record.status,'registered');
    assert.deepEqual(record.entries,[{relativePath:'收藏.md',hash:file.hash}]);
    assert.equal(fs.readFileSync(path.join(external,'收藏.md'),'utf8'),'显式关联收藏');
    assert.equal(fs.readFileSync(path.join(root,'13_X收藏','历史.md'),'utf8'),'作者历史收藏');
});
