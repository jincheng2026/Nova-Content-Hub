import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';

const source = new URL('../src/bridge/handoff.js', import.meta.url);
const target = new URL('../../workbench/prototype/shared/handoff.js', import.meta.url);
const header = '// Generated by plugin-src/scripts/sync-bridge.mjs; edit plugin-src/src/bridge/handoff.js.\n';

export async function syncBridge(check = false) {
    for (const [from, to, prefix] of [
        [source, target, header],
        [source, new URL('../src/lib/browser-import/legacy/shared/handoff.js', import.meta.url), header],
        [new URL('../src/lib/browser-import/legacy/core.js', import.meta.url), new URL('../../workbench/prototype/core.js', import.meta.url), '// Generated by plugin-src/scripts/sync-bridge.mjs; edit plugin-src/src/lib/browser-import/legacy/core.js.\n']
    ]) {
        const expected = prefix + await readFile(from, 'utf8');
        if (check) {
            if (await readFile(to, 'utf8') !== expected) throw Error('Generated module drift; run node plugin-src/scripts/sync-bridge.mjs');
        } else {
            await mkdir(new URL('./', to), {recursive: true});
            await writeFile(to, expected);
        }
    }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const args = process.argv.slice(2);
    if (args.length > 1 || args.length === 1 && args[0] !== '--check') throw Error('Use sync-bridge.mjs [--check]');
    await syncBridge(args[0] === '--check');
}
